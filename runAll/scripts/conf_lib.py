def resolve_conf_app_dir(root: Path, app: str) -> Path:
    """Resolve legacy app key or short name to conf/<functional>/<app>/ directory."""
    key = (app or "").strip().replace("\\", "/").strip("/")
    mapped = JSON_KEY_TO_APP_DIR.get(key, key)
    direct = root / "conf" / mapped
    if (direct / "sync.manifest.yaml").is_file():
        return direct
    tail = key.split("/")[-1]
    conf_root = root / "conf"
    if conf_root.is_dir():
        for func_dir in sorted(conf_root.iterdir()):
            if not func_dir.is_dir() or func_dir.name.startswith("."):
                continue
            candidate = func_dir / tail
            if (candidate / "sync.manifest.yaml").is_file():
                return candidate
    return direct


def generated_header(app_rel_path: str, source: str) -> str:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rel = app_rel_path.strip("/")
    return (
        f"# GENERATED by conf/{rel}/sync.sh — DO NOT EDIT\n"
        f"# source: {source}\n"
        f"# synced_at: {ts}\n"
    )
