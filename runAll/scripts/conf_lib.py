def _explicit_config_root(raw: str) -> Path | None:
    """CONF_ROOT may be the conf dir (has base.yaml) or deploy root (has conf/base.yaml)."""
    text = (raw or "").strip()
    if not text:
        return None
    p = Path(text).expanduser()
    if (p / "base.yaml").is_file():
        return p.parent.resolve()
    if (p / "conf" / "base.yaml").is_file():
        return p.resolve()
    return None


def repo_root() -> Path:
    import os

    for key in ("CONF_ROOT", "DEPLOY_ROOT"):
        hit = _explicit_config_root(os.environ.get(key, ""))
        if hit is not None:
            return hit

    anchors = [
        Path.cwd(),
        Path(__file__).resolve(),
    ]
    for start in anchors:
        here = start if start.is_dir() else start.parent
        for _ in range(6):
            # OPT-20260806-057: django 目录退役，锚点切到 conf/base.yaml
            if (here / "conf" / "base.yaml").is_file():
                return here
            here = here.parent
    raise FileNotFoundError("cannot locate monorepo root (expected conf/base.yaml)")


def kebab_to_camel(name: str) -> str:
    parts = name.replace("_", "-").split("-")
    if not parts:
        return name
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def load_yaml(path: Path) -> dict[str, Any]:
    if yaml is None:
        raise RuntimeError("PyYAML required: pip install pyyaml")
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else {}


def dump_yaml(path: Path, data: dict[str, Any]) -> None:
    if yaml is None:
        raise RuntimeError("PyYAML required")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        yaml.dump(data, allow_unicode=True, default_flow_style=False, sort_keys=False),
        encoding="utf-8",
    )


def deep_merge(base: dict[str, Any], overlay: dict[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for k, v in overlay.items():
        if k in out and isinstance(out[k], dict) and isinstance(v, dict):
            out[k] = deep_merge(out[k], v)
        elif k in out and isinstance(out[k], list) and isinstance(v, list):
            merged = list(out[k])
            for i, ov in enumerate(v):
                if i < len(merged) and isinstance(merged[i], dict) and isinstance(ov, dict):
                    merged[i] = deep_merge(merged[i], ov)
                elif i < len(merged):
                    merged[i] = ov
                else:
                    merged.append(ov)
            out[k] = merged
        else:
            out[k] = v
    return out


